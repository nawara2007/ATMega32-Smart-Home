#include "ADC.h"

static u8 is_initialized = 0;

void ADC_voidInit( void )
{
	if (is_initialized)
	{
		return;
	}
	
	#if(ADC_VREF == AREF)
		CLR_BIT(ADMUX, ADMUX_REFS0);
		CLR_BIT(ADMUX, ADMUX_REFS1);
	#elif(ADC_VREF == AVCC)
		SET_BIT(ADMUX, ADMUX_REFS0);
		CLR_BIT(ADMUX, ADMUX_REFS1);
	#elif (ADC_VREF == INTERNAL_2_56)
		SET_BIT(ADMUX, ADMUX_REFS0);
		SET_BIT(ADMUX, ADMUX_REFS1);
	#endif
	
	#if (ADC_ADJUSTMENT == RIGHT_ADJUSTMENT)
		CLR_BIT(ADMUX, ADMUX_ADLAR);
	#elif (ADC_ADJUSTMENT == LEFT_ADJUSTMENT)
		SET_BIT(ADMUX, ADMUX_ADLAR);
	#endif
	
	#if (ADC_TRIGGERING_SOURCE == ADC_SINGLE_CONVERSION)
		CLR_BIT(ADCSRA, ADCSRA_ADATE);
		CLR_BIT(SFIOR, SFIOR_ADTS0);
		CLR_BIT(SFIOR, SFIOR_ADTS1);
		CLR_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_FREE_RUNNING)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		CLR_BIT(SFIOR, SFIOR_ADTS0);
		CLR_BIT(SFIOR, SFIOR_ADTS1);
		CLR_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_ANALOG_COMPARATOR)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		SET_BIT(SFIOR, SFIOR_ADTS0);
		CLR_BIT(SFIOR, SFIOR_ADTS1);
		CLR_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_EXTI0)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		CLR_BIT(SFIOR, SFIOR_ADTS0);
		SET_BIT(SFIOR, SFIOR_ADTS1);
		CLR_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_TIM0_CTC)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		SET_BIT(SFIOR, SFIOR_ADTS0);
		SET_BIT(SFIOR, SFIOR_ADTS1);
		CLR_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_TIM0_OVF)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		CLR_BIT(SFIOR, SFIOR_ADTS0);
		CLR_BIT(SFIOR, SFIOR_ADTS1);
		SET_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_TIM1_CTC_CHANNEL_B)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		SET_BIT(SFIOR, SFIOR_ADTS0);
		CLR_BIT(SFIOR, SFIOR_ADTS1);
		SET_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_TIM1_OVF)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		CLR_BIT(SFIOR, SFIOR_ADTS0);
		SET_BIT(SFIOR, SFIOR_ADTS1);
		SET_BIT(SFIOR, SFIOR_ADTS2);
	#elif(ADC_TRIGGERING_SOURCE == ADC_TIM1_ICU)
		SET_BIT(ADCSRA, ADCSRA_ADATE);
		SET_BIT(SFIOR, SFIOR_ADTS0);
		SET_BIT(SFIOR, SFIOR_ADTS1);
		SET_BIT(SFIOR, SFIOR_ADTS2);

	#endif
	
	ADC_voidSetPrescaler();
	
	SET_BIT(ADCSRA, ADCSRA_ADEN);
	
	is_initialized = 1;
}

void ADC_voidStartConversion  (u8 Copy_u8Channel_num)
{
	//ADMUX_MASK is defined as 0001 1111
	ADMUX = (ADMUX & ~ADMUX_MASK) | (Copy_u8Channel_num & ADMUX_MASK); // to set the least signifcant 5 bits(the bits of setting the channel) at one time
	
	// clear flag by writing 1 to it
	SET_BIT(ADCSRA, ADCSRA_ADIF);
	
	//begin conversion
	SET_BIT(ADCSRA, ADCSRA_ADSC);
}

u16 ADC_u16GetResultSync(u8 Copy_u8Channel_num)
{
	ADC_voidStartConversion(Copy_u8Channel_num);
	
	// wait until conversion is complete as hardware clears ADSC when done
	while (GET_BIT(ADCSRA, ADCSRA_ADSC));
		
	return ADC_u16GetResult();
}

u16 ADC_u16GetResult (void)
{
	#if (ADC_ADJUSTMENT == RIGHT_ADJUSTMENT)
		u16 result = ADCL;
		result |= ((u16)ADCH << 8);
		return result;
	#elif (ADC_ADJUSTMENT == LEFT_ADJUSTMENT)
		return ADCH;
	#endif
}

void ADC_voidSetPrescaler ()
{
	// ADCSRA_MASK is defined as 0000 0111
	#if (ADC_PRESCALLER == ADC_PRE_2)
		CLR_BIT(ADCSRA, ADCSRA_ADPS0);
		CLR_BIT(ADCSRA, ADCSRA_ADPS1);
		CLR_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_4)
		CLR_BIT(ADCSRA, ADCSRA_ADPS0);
		SET_BIT(ADCSRA, ADCSRA_ADPS1);
		CLR_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_8)
		SET_BIT(ADCSRA, ADCSRA_ADPS0);
		SET_BIT(ADCSRA, ADCSRA_ADPS1);
		CLR_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_16)
		CLR_BIT(ADCSRA, ADCSRA_ADPS0);
		CLR_BIT(ADCSRA, ADCSRA_ADPS1);
		SET_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_32)
		SET_BIT(ADCSRA, ADCSRA_ADPS0);
		CLR_BIT(ADCSRA, ADCSRA_ADPS1);
		SET_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_64)
		CLR_BIT(ADCSRA, ADCSRA_ADPS0);
		SET_BIT(ADCSRA, ADCSRA_ADPS1);
		SET_BIT(ADCSRA, ADCSRA_ADPS2);
	#elif (ADC_PRESCALLER == ADC_PRE_128)
		SET_BIT(ADCSRA, ADCSRA_ADPS0);
		SET_BIT(ADCSRA, ADCSRA_ADPS1);
		SET_BIT(ADCSRA, ADCSRA_ADPS2);
	#endif
}

void ADC_enableInt (void)
{
	SET_BIT(ADCSRA, ADCSRA_ADIE);
}

void ADC_disableInt (void)
{
	CLR_BIT(ADCSRA, ADCSRA_ADIE);
}

static void (*ADC_pvoidCallBack)(void) = NULL;
	
void ADC_setCallBack (void(*CopyFuncPtr) (void))
{
	if (CopyFuncPtr != NULL)
	{
		ADC_pvoidCallBack = CopyFuncPtr;
	}
}

ISR(ADC_vect)
{
	if (ADC_pvoidCallBack != NULL)
	{
		ADC_pvoidCallBack();
	}
}
